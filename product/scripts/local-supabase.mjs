import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { assertLocalUrl } from "./lib/local-only.mjs";

const projectDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const action = process.argv[2] ?? "status";
const allowedActions = new Set(["start", "stop", "reset", "status"]);

if (!allowedActions.has(action)) {
  throw new Error(`Unsupported local Supabase action: ${action}`);
}

function run(args, options = {}) {
  const result = spawnSync("supabase", args, {
    cwd: projectDir,
    encoding: "utf8",
    stdio: options.capture ? "pipe" : "inherit",
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    if (options.capture && result.stderr) process.stderr.write(result.stderr);
    process.exit(result.status ?? 1);
  }
  return result.stdout ?? "";
}

function parseStatusEnv(output) {
  return Object.fromEntries(output.split(/\r?\n/).flatMap((line) => {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (!match) return [];
    const value = match[2].replace(/^"|"$/g, "");
    return [[match[1], value]];
  }));
}

function writeLocalEnvironment() {
  const status = parseStatusEnv(run(["status", "-o", "env"], { capture: true }));
  const apiUrl = status.API_URL;
  const dbUrl = status.DB_URL;
  assertLocalUrl("API_URL", apiUrl);
  assertLocalUrl("DB_URL", dbUrl);
  if (!status.ANON_KEY || !status.SERVICE_ROLE_KEY) {
    throw new Error("Supabase CLI did not return local API keys");
  }

  const environmentPath = path.join(projectDir, ".env.ingestion.local");
  const existing = existsSync(environmentPath)
    ? parseStatusEnv(readFileSync(environmentPath, "utf8"))
    : {};
  const preserved = (name) => process.env[name]?.trim() || existing[name] || "";
  const lines = [
    "# Generated by npm run local:start. Do not commit this file.",
    `SUPABASE_URL=${apiUrl}`,
    `NEXT_PUBLIC_SUPABASE_URL=${apiUrl}`,
    `SUPABASE_ANON_KEY=${status.ANON_KEY}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${status.ANON_KEY}`,
    `SUPABASE_SECRET_KEY=${status.SERVICE_ROLE_KEY}`,
    `SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY}`,
    `POSTGRES_URL=${dbUrl}`,
    `POSTGRES_URL_NON_POOLING=${dbUrl}`,
    `OPENAI_API_KEY=${preserved("OPENAI_API_KEY")}`,
    `DECODO_API_KEY=${preserved("DECODO_API_KEY")}`,
    `FIRECRAWL_API_KEY=${preserved("FIRECRAWL_API_KEY")}`,
    `SCRAPERAPI_API_KEY=${preserved("SCRAPERAPI_API_KEY")}`,
    `SEC_USER_AGENT=${preserved("SEC_USER_AGENT")}`,
    "",
  ];
  writeFileSync(environmentPath, lines.join("\n"), { mode: 0o600 });
  console.log("Wrote .env.ingestion.local with local-only Supabase endpoints.");
}

if (action === "start") {
  run(["start"]);
  writeLocalEnvironment();
} else if (action === "reset") {
  run(["db", "reset", "--local"]);
  writeLocalEnvironment();
} else if (action === "status") {
  const status = parseStatusEnv(run(["status", "-o", "env"], { capture: true }));
  const apiUrl = assertLocalUrl("API_URL", status.API_URL);
  const dbUrl = assertLocalUrl("DB_URL", status.DB_URL);
  console.log(`Local Supabase is running (API ${apiUrl.hostname}:${apiUrl.port}, DB ${dbUrl.hostname}:${dbUrl.port}).`);
} else {
  run([action]);
}
